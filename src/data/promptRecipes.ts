/**
 * プロンプト生成のレシピ（カテゴリごとの骨組み）
 * ----------------------------------------------------------------
 * ユーザーの回答はここに定義した骨組みへ整理して流し込まれます。
 * targetOverrides で「出力先のAI」ごとに内容を差し替えられます。
 */

export type RecipeSection = 'steps' | 'quality' | 'checks' | 'features';

